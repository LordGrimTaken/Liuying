#!/usr/bin/env node
// Move accounts and sync data from the old Render Postgres into Cloudflare D1.
//
//   export   DATABASE_URL=... node scripts/migrate-render-to-d1.mjs export [--out legacy-export.sql]
//   reparent node scripts/migrate-render-to-d1.mjs reparent --from OLDNAME --to NEWNAME [--take-username] [--out reparent.sql]
//
// export: read-only against Postgres (SELECT only). Writes a SQL file for `wrangler d1 execute`. It never prints
//   DATABASE_URL and never writes password hashes: scrypt hashes cannot be verified on the Workers Free plan, so every
//   imported user gets password_hash = NULL and needs_new_password = 1 (they cannot log in with a password until they
//   set a new one). Recovery-code hashes are plain SHA-256, so they are carried over and a recovery code still works.
//   Sessions are not migrated (everyone signs in again).
// reparent: pure SQL generator (no database access). After the owner signs up on the new site under any name, this
//   moves the old account's sources/library/progress/settings to the new account, deletes the imported shell, and with
//   --take-username renames the new account to the old username.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { normalizeUsername, usernameKey, validateUsername } from '../src/auth.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const [cmd, ...rest] = process.argv.slice(2);
const flag = (name, def) => { const i = rest.indexOf(`--${name}`); return i >= 0 ? (rest[i + 1] && !rest[i + 1].startsWith('--') ? rest[i + 1] : true) : def; };
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(Math.trunc(v)) : typeof v === 'boolean' ? (v ? '1' : '0') : `'${String(v).replace(/'/g, "''")}'`);
const ms = (d) => (d === null || d === undefined ? null : new Date(d).getTime());
const row = (vals) => `(${vals.map(q).join(', ')})`;

function insertBatches(table, cols, rows, size = 50) {
  const out = [];
  for (let i = 0; i < rows.length; i += size) {
    out.push(`INSERT OR IGNORE INTO ${table} (${cols.join(', ')}) VALUES\n${rows.slice(i, i + size).map(row).join(',\n')};`);
  }
  return out;
}

async function exportCmd() {
  const url = process.env.DATABASE_URL;
  if (!url) { console.error('Set DATABASE_URL (the Render Postgres external URL) in the environment.'); process.exit(2); }
  const outFile = flag('out', 'legacy-export.sql');
  const require = createRequire(path.resolve(here, '../../server/package.json'));
  const pg = require('pg');
  const client = new pg.Client({ connectionString: url, ssl: /^(1|true)$/i.test(process.env.DATABASE_SSL || '') ? { rejectUnauthorized: false } : undefined });
  try { await client.connect(); } catch (e) {
    console.error(`Could not connect to Postgres: ${String(e.message).split(url)[0].replace(/postgres(ql)?:\/\/\S+/gi, '[redacted]')}`); process.exit(1);
  }
  const all = async (sql) => (await client.query(sql)).rows;
  try {
    await client.query('BEGIN READ ONLY');
    const users = await all('SELECT id, username, username_lower, created_at, recovery_hash, recovery_created_at FROM users ORDER BY created_at');
    const sources = await all('SELECT user_id, url, position, enabled FROM user_sources ORDER BY user_id, position');
    const library = await all('SELECT user_id, id, type, name, poster, added_at FROM user_library');
    const progress = await all('SELECT user_id, media_id, episode_id, position_ms, duration_ms, watched, dismissed, updated_at FROM user_progress');
    const settings = await all('SELECT user_id, data, updated_at FROM user_settings');
    await client.query('COMMIT');

    const sql = [
      '-- Generated by scripts/migrate-render-to-d1.mjs. Contains user data (no passwords). Do not commit.',
      ...insertBatches('users', ['id', 'username', 'username_lower', 'password_hash', 'created_at', 'recovery_hash', 'recovery_created_at', 'needs_new_password'],
        users.map((u) => [u.id, normalizeUsername(u.username), usernameKey(u.username), null, ms(u.created_at), u.recovery_hash, ms(u.recovery_created_at), 1])),
      ...insertBatches('user_sources', ['user_id', 'url', 'position', 'enabled'], sources.map((s) => [s.user_id, s.url, Number(s.position), !!s.enabled])),
      ...insertBatches('user_library', ['user_id', 'id', 'type', 'name', 'poster', 'added_at'],
        library.map((l) => [l.user_id, l.id, l.type, l.name, l.poster, ms(l.added_at)])),
      ...insertBatches('user_progress', ['user_id', 'media_id', 'episode_id', 'position_ms', 'duration_ms', 'watched', 'dismissed', 'updated_at'],
        progress.map((p) => [p.user_id, p.media_id, p.episode_id, Number(p.position_ms), Number(p.duration_ms), !!p.watched, !!p.dismissed, Number(p.updated_at)]), 40),
      ...insertBatches('user_settings', ['user_id', 'data', 'updated_at'], settings.map((s) => [s.user_id, s.data, ms(s.updated_at)])),
      '',
    ].join('\n');
    fs.writeFileSync(outFile, sql);
    const bad = users.filter((u) => validateUsername(u.username));
    console.log(`Wrote ${outFile}: ${users.length} users, ${sources.length} sources, ${library.length} library items, ${progress.length} progress rows, ${settings.length} settings.`);
    if (bad.length) console.log(`Note: ${bad.length} username(s) do not pass the current username rules but were exported as-is.`);
    console.log(`Apply with: npx wrangler d1 execute liuying --remote --file ${outFile}`);
  } finally {
    await client.end().catch(() => {});
  }
}

function reparentCmd() {
  const from = flag('from'); const to = flag('to');
  if (typeof from !== 'string' || typeof to !== 'string') { console.error('Usage: reparent --from OLDNAME --to NEWNAME [--take-username] [--out reparent.sql]'); process.exit(2); }
  if (validateUsername(from) || validateUsername(to)) { console.error('Both usernames must be valid Liuying usernames.'); process.exit(2); }
  const oldKey = usernameKey(from); const newKey = usernameKey(to);
  if (oldKey === newKey) { console.error('--from and --to are the same account; just sign up under a different name first.'); process.exit(2); }
  const legacy = `legacy:${oldKey}`;
  const idOf = (key) => `(SELECT id FROM users WHERE username_lower = ${q(key)})`;
  const sql = [
    `-- Move the imported account "${from}" onto the new account "${to}".`,
    // Park the imported shell under a key no one can sign up with, and only if it really is an imported account.
    `UPDATE users SET username_lower = ${q(legacy)} WHERE username_lower = ${q(oldKey)} AND needs_new_password = 1 AND password_hash IS NULL;`,
    ...['user_sources', 'user_library', 'user_progress', 'user_settings'].map((t) =>
      `UPDATE OR IGNORE ${t} SET user_id = ${idOf(newKey)} WHERE user_id = ${idOf(legacy)};`),
    // Anything left (rows that collided with data already in the new account) goes with the shell (ON DELETE CASCADE).
    // Guarded: if the new account does not exist yet nothing is deleted (run the file again after signing up).
    `DELETE FROM users WHERE username_lower = ${q(legacy)} AND EXISTS (SELECT 1 FROM users WHERE username_lower = ${q(newKey)});`,
    ...(flag('take-username') ? [`UPDATE users SET username = ${q(normalizeUsername(from))}, username_lower = ${q(oldKey)} WHERE username_lower = ${q(newKey)};`] : []),
    '',
  ].join('\n');
  const outFile = flag('out', 'reparent.sql');
  fs.writeFileSync(outFile, sql);
  console.log(`Wrote ${outFile}. Apply with: npx wrangler d1 execute liuying --remote --file ${outFile}`);
}

if (cmd === 'export') await exportCmd();
else if (cmd === 'reparent') reparentCmd();
else { console.error('Usage: migrate-render-to-d1.mjs export|reparent ...  (see the header of this file)'); process.exit(2); }
